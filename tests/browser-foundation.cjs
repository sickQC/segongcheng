  await page.getByRole('button',{name:'登录 →',exact:true}).click();
  await page.getByRole('heading',{name:'P1 浏览器验收课程',exact:true}).waitFor();
  await page.locator('article').filter({hasText:'P1 浏览器验收课程'}).getByRole('button',{name:'查看课程 →'}).click();
